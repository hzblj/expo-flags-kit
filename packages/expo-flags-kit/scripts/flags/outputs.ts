import {readdirSync, readFileSync} from 'node:fs'
import path from 'node:path'

import {type Flag, normalizeFlag} from './normalize'
import {toSvg} from './svg'
import {drawableName, toVectorDrawable} from './vectorDrawable'

export const ROOT = path.resolve(import.meta.dirname, '../..')

export const SOURCE_DIRECTORY = 'flagkit/svg'

// Directories the generator owns completely; anything in them that it doesn't produce is stale.
export const GENERATED_DIRECTORIES = ['android/src/main/res/drawable', 'assets/flags', 'ios/Flags.xcassets']

const KOTLIN_PACKAGE = 'com.hzblj.expoflagskit'

const IMAGESET_INFO = {author: 'xcode', version: 1}

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`

export const readFlags = (root = ROOT) =>
  readdirSync(path.join(root, SOURCE_DIRECTORY))
    .filter(file => file.endsWith('.svg'))
    .map(file => {
      const code = path.basename(file, '.svg')
      const source = readFileSync(path.join(root, SOURCE_DIRECTORY, file), 'utf8')

      return {code, source, ...normalizeFlag(code, source)}
    })
    .sort((a, b) => (a.code < b.code ? -1 : 1))

const codesModule = (flags: Flag[]) =>
  [
    '// Generated by scripts/generate.ts from the FlagKit sources in flagkit/svg. Do not edit.',
    '',
    'export const FLAG_CODES = [',
    ...flags.map(flag => `  '${flag.code}',`),
    '] as const',
    '',
  ].join('\n')

const webAssetsModule = (flags: Flag[]) =>
  [
    '// Generated by scripts/generate.ts. Do not edit.',
    '',
    "import type {ImageSourcePropType} from 'react-native'",
    '',
    "import type {FlagCode} from './codes'",
    '',
    'export const FLAG_ASSETS: Record<FlagCode, ImageSourcePropType> = {',
    ...flags.map(flag => {
      const key = /^[A-Z]+$/.test(flag.code) ? flag.code : `'${flag.code}'`

      return `  ${key}: require('../assets/flags/${flag.code}.svg'),`
    }),
    '}',
    '',
  ].join('\n')

const kotlinDrawables = (flags: Flag[]) =>
  [
    '// Generated by scripts/generate.ts. Do not edit.',
    '',
    `package ${KOTLIN_PACKAGE}`,
    '',
    'internal object FlagDrawables {',
    '  // Direct R references keep every flag through resource shrinking, and avoid getIdentifier lookups.',
    '  fun resourceId(code: String): Int? = when (code) {',
    ...flags.map(flag => `    "${flag.code}" -> R.drawable.${drawableName(flag.code)}`),
    '    else -> null',
    '  }',
    '}',
    '',
  ].join('\n')

// Every generated file, keyed by its path relative to the package root.
export const generateOutputs = (root = ROOT): Map<string, string> => {
  const flags = readFlags(root).map(({flag}) => flag)
  const outputs = new Map<string, string>()

  outputs.set('ios/Flags.xcassets/Contents.json', json({info: IMAGESET_INFO}))

  for (const flag of flags) {
    const svg = toSvg(flag)

    outputs.set(`ios/Flags.xcassets/${flag.code}.imageset/${flag.code}.svg`, svg)
    outputs.set(
      `ios/Flags.xcassets/${flag.code}.imageset/Contents.json`,
      json({
        images: [{filename: `${flag.code}.svg`, idiom: 'universal'}],
        info: IMAGESET_INFO,
        properties: {'preserves-vector-representation': true},
      })
    )
    outputs.set(`assets/flags/${flag.code}.svg`, svg)
    outputs.set(`android/src/main/res/drawable/${drawableName(flag.code)}.xml`, toVectorDrawable(flag))
  }

  outputs.set(`android/src/main/java/${KOTLIN_PACKAGE.replace(/\./g, '/')}/FlagDrawables.kt`, kotlinDrawables(flags))
  outputs.set('src/codes.generated.ts', codesModule(flags))
  outputs.set('src/assets.web.generated.ts', webAssetsModule(flags))

  return outputs
}
